function icon(name, opts = {}) {
  const paths = ICONS[name] || ICONS['help-circle'];
  const size = opts.size ?? 20;
  const cls = opts.class ? `icon ${opts.class}` : 'icon';
  const title = opts.title ? ` aria-label="${opts.title}" role="img"` : ' aria-hidden="true"';
  return `<svg class="${cls}" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"${title}>${paths}</svg>`;
}

function setIcon(el, name, size = 24, extraClass = '') {
  const node = typeof el === 'string' ? document.querySelector(el) : el;
  if (!node) return;
  node.innerHTML = icon(name, { size, class: extraClass });
}

function btnIcon(name, size = 18) {
  return `<span class="btn-icon">${icon(name, { size })}</span>`;
}

function headingIcon(name, size = 20) {
  return icon(name, { size, class: 'heading-icon' });
}

function decorateContentIcons(html) {
  return html
    .replace(/<div class="tip-box">💡 /g, `<div class="tip-box">${icon('lightbulb', { size: 18, class: 'content-leading-icon' })} `)
    .replace(/<div class="tip-box">⚠️ /g, `<div class="tip-box">${icon('triangle-alert', { size: 18, class: 'content-leading-icon warning' })} `)
    .replace(/<h3>🛑 /g, `<h3>${headingIcon('octagon')} `)
    .replace(/<h3>🅿️ /g, `<h3>${headingIcon('circle-parking')} `)
    .replace(/<h3>❌ /g, `<h3>${headingIcon('circle-x', 20)} `)
    .replace(/<h3>✅ /g, `<h3>${headingIcon('circle-check', 20)} `)
    .replace(/<h3>🚗 /g, `<h3>${headingIcon('car', 20)} `)
    .replace(/<h3>🏍️ /g, `<h3>${headingIcon('bike', 20)} `)
    .replace(/ ↔️/g, ` ${icon('arrows-left-right', { size: 16, class: 'heading-icon' })}`)
    .replace(/ ⬆️/g, ` ${icon('arrow-up', { size: 16, class: 'heading-icon' })}`)
    .replace(/Arms ↔️/g, `Arms ${icon('arrows-left-right', { size: 16, class: 'heading-icon' })}`)
    .replace(/Arms ⬆️/g, `Arms ${icon('arrow-up', { size: 16, class: 'heading-icon' })}`)
    .replace(/<li>❌ /g, `<li class="list-item-with-icon">${icon('x', { size: 16, class: 'list-leading-icon danger' })} `)
    .replace(/<li>✅ /g, `<li class="list-item-with-icon">${icon('check', { size: 16, class: 'list-leading-icon success' })} `);
}

function resultsIconName(passed, pct) {
  if (passed) return 'trophy';
  if (pct >= 70) return 'book-marked';
  return 'target';
}
